pub fn paint(painter: &egui::Painter, pos: Pos2, icon: Icon, size: f32, color: Color32) {
    painter.text(
        pos,
        Align2::CENTER_CENTER,
        icon.glyph(),
        FontId::new(size, FontFamily::Name(FAMILY.into())),
        color,
    );
}
