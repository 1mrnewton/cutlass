        let mut factory = DecodeFactory::new();
        register_decoders(&mut factory);
        let params = CodecParams::video(CodecId::Av1, 16, 16);
        let decoder = factory.open(&params).expect("open");
        assert_eq!(decoder.codec(), CodecId::Av1);
