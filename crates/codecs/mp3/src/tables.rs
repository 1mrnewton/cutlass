/// Long-band starts (line index), 23 entries, per rate table.
pub(crate) const fn long_starts(table: usize) -> [u16; 23] {
    let widths = LONG_WIDTHS[table];
    let mut starts = [0u16; 23];
    let mut band = 0;
    while band < 22 {
        starts[band + 1] = starts[band] + widths[band];
        band += 1;
    }
    starts
}

/// Short-band starts within one window, 14 entries, per rate table.
pub(crate) const fn short_starts(table: usize) -> [u16; 14] {
    let widths = SHORT_WIDTHS[table];
    let mut starts = [0u16; 14];
    let mut band = 0;
    while band < 13 {
        starts[band + 1] = starts[band] + widths[band];
        band += 1;
    }
    starts
}

