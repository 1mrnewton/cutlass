//! Normative Layer III tables.
//!
//! Provenance:
//! - Scalefactor band widths: ISO/IEC 11172-3 Table 3-B.8 (32, 44.1, 48 kHz)
//!   and ISO/IEC 13818-3 Table B.2 (16, 22.05, 24 kHz). MPEG-2.5 at 11.025
//!   and 12 kHz uses the 16 kHz widths; 8 kHz uses the doubled long widths
//!   that the Fraunhofer extension, mpg123, and FFmpeg 8.1.1 all decode.
//! - `pretab`: ISO/IEC 11172-3 Table 3-B.6.
//! - `slen1`/`slen2`: ISO/IEC 11172-3 2.4.2.7 (`scalefac_compress`).
//! - LSF scalefactor partitions: ISO/IEC 13818-3 clause 2.4.3.2 (`nr_of_sfb_block`),
//!   as tabulated in the Fraunhofer "MPEG Layer-3 Bitstream Syntax and
//!   Decoding" note.
//! - Synthesis window `D[i]`: ISO/IEC 11172-3 Table 3-B.3. The standard
//!   prints nine decimals; every entry is an integer multiple of 2^-16, so
//!   the half window is stored here as those integers (`D[i] * 65536`).
//! - Alias-reduction coefficients `c[i]`: ISO/IEC 11172-3 Table 3-B.9.
//! - Huffman codes: ISO/IEC 11172-3 Table 3-B.7, stored in canonical form.
//!   Each table lists `(length, xy)` in increasing code order; the code of
//!   entry `n` is the previous code plus one at the previous length, so the
//!   lengths alone rebuild every codeword. The order and lengths were
//!   transcribed from FFmpeg 8.1.1 `libavcodec/mpegaudiodec_common.c`,
//!   which publishes the standard table in that form. `huffman.rs` tests
//!   that each table is prefix-free and complete.

