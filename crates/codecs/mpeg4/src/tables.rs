/// Intra DC scaler of a luminance block for `quantiser_scale` 1 to 31
/// (Table 7-1).
pub(crate) fn dc_scaler_luma(q: u32) -> i32 {
    match q {
        0..=4 => 8,
        5..=8 => 2 * q as i32,
        9..=24 => q as i32 + 8,
        _ => 2 * q as i32 - 16,
    }
}

/// Intra DC scaler of a chrominance block (Table 7-1).
pub(crate) fn dc_scaler_chroma(q: u32) -> i32 {
    match q {
        0..=4 => 8,
        5..=24 => (q as i32 + 13) / 2,
        _ => q as i32 - 6,
    }
}

