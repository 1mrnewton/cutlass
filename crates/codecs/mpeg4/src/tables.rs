//! Normative tables of ISO/IEC 14496-2 (MPEG-4 Visual), Annex B, and the
//! VLC decoders built from them.
//!
//! Codes are written as `(length, code)` with the code in binary, so each
//! entry reads like the standard's table.

use std::sync::OnceLock;

use crate::vlc::Vlc;

/// One transform coefficient code: run of zeros, level, and whether it is
/// the block's last coefficient.
#[derive(Clone, Copy)]
pub(crate) struct Tcoef {
    pub(crate) len: u8,
    pub(crate) code: u16,
    pub(crate) last: bool,
    pub(crate) run: u8,
    pub(crate) level: u8,
}

const fn t(len: u8, code: u16, last: u8, run: u8, level: u8) -> Tcoef {
    Tcoef {
        len,
        code,
        last: last == 1,
        run,
        level,
    }
}

