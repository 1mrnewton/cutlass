/// A coefficient table with its decoder and the limits the escape modes
/// use.
pub(crate) struct CoefTable {
    pub(crate) codes: &'static [Tcoef],
    /// Symbols index `codes`; the escape is `codes.len()`.
    pub(crate) vlc: Vlc,
    /// Largest level a code carries, by `[last][run]`.
    pub(crate) max_level: [[u8; 64]; 2],
    /// Largest run a code carries, by `[last][level]`.
    pub(crate) max_run: [[u8; 64]; 2],
    /// `(length, code)` by `last * 2048 + run * 32 + level`; length 0
    /// means no code.
    encode: Vec<(u8, u16)>,
}

impl CoefTable {
    fn new(codes: &'static [Tcoef], escape: (u8, u16)) -> Self {
        let mut triples: Vec<(u8, u16, u16)> = codes
            .iter()
            .enumerate()
            .map(|(i, c)| (c.len, c.code, i as u16))
            .collect();
        triples.push((escape.0, escape.1, codes.len() as u16));
        let vlc = Vlc::new(&triples).unwrap_or_else(|_| Vlc::empty());
        let mut max_level = [[0u8; 64]; 2];
        let mut max_run = [[0u8; 64]; 2];
        let mut encode = vec![(0u8, 0u16); 4096];
        for c in codes {
            let last = usize::from(c.last);
            let (run, level) = (usize::from(c.run), usize::from(c.level));
            if let Some(m) = max_level[last].get_mut(run) {
                *m = (*m).max(c.level);
            }
            if let Some(m) = max_run[last].get_mut(level) {
                *m = (*m).max(c.run);
            }
            if run < 64
                && level < 32
                && let Some(slot) = encode.get_mut(last * 2048 + run * 32 + level)
            {
                *slot = (c.len, c.code);
            }
        }
        Self {
            codes,
            vlc,
            max_level,
            max_run,
            encode,
        }
    }

    /// The code of `(last, run, level)` with `level` positive, if the
    /// table has one.
    #[inline]
    pub(crate) fn code(&self, last: bool, run: usize, level: u32) -> Option<(u8, u16)> {
        if run >= 64 || level >= 32 || level == 0 {
            return None;
        }
        let index = usize::from(last) * 2048 + run * 32 + level as usize;
        self.encode.get(index).copied().filter(|c| c.0 != 0)
    }
}

/// Every decoder table, built once.
pub(crate) struct Tables {
    pub(crate) intra: CoefTable,
    pub(crate) inter: CoefTable,
    pub(crate) intra_rvlc: CoefTable,
    pub(crate) inter_rvlc: CoefTable,
    pub(crate) dc_luma: Vlc,
    pub(crate) dc_chroma: Vlc,
    pub(crate) mcbpc_intra: Vlc,
    pub(crate) mcbpc_inter: Vlc,
    pub(crate) cbpy: Vlc,
    pub(crate) mvd: Vlc,
    pub(crate) mb_type_b: Vlc,
    pub(crate) dmv_length: Vlc,
}

fn build() -> Tables {
    let indexed = |codes: &[(u8, u16)]| Vlc::indexed(codes).unwrap_or_else(|_| Vlc::empty());
    let inter_mcbpc: Vec<(u8, u16, u16)> = MCBPC_INTER
        .iter()
        .map(|&(symbol, len, code)| (len, code, symbol))
        .collect();
    Tables {
        intra: CoefTable::new(&INTRA_TCOEF, TCOEF_ESCAPE),
        inter: CoefTable::new(&INTER_TCOEF, TCOEF_ESCAPE),
        intra_rvlc: CoefTable::new(&INTRA_RVLC, RVLC_ESCAPE),
        inter_rvlc: CoefTable::new(&INTER_RVLC, RVLC_ESCAPE),
        dc_luma: indexed(&DC_LUMA),
        dc_chroma: indexed(&DC_CHROMA),
        mcbpc_intra: indexed(&MCBPC_INTRA),
        mcbpc_inter: Vlc::new(&inter_mcbpc).unwrap_or_else(|_| Vlc::empty()),
        cbpy: indexed(&CBPY),
        mvd: indexed(&MVD),
        mb_type_b: indexed(&MB_TYPE_B),
        dmv_length: indexed(&DMV_LENGTH),
    }
}

/// The shared tables.
pub(crate) fn tables() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(build)
}

