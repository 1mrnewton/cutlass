/// One NLSF codebook (`silk_NLSF_CB_struct`).
#[derive(Debug)]
pub(crate) struct NlsfCodebook {
    /// First-stage vectors.
    pub n_vectors: usize,
    /// LPC order, 10 or 16.
    pub order: usize,
    /// `quantStepSize_Q16`.
    pub quant_step_size_q16: i32,
    /// First-stage codebook, `n_vectors * order` entries in Q8.
    pub cb1_nlsf_q8: &'static [u8],
    /// First-stage index tables, one of `n_vectors` entries per voicing class.
    pub cb1_icdf: &'static [u8],
    /// Backward predictor coefficients in Q8, two rows of `order - 1`
    /// (`pred_Q8`).
    pub pred_q8: &'static [u8],
    /// Packed second-stage table and predictor selectors.
    pub ec_sel: &'static [u8],
    /// Second-stage index tables, 9 entries each.
    pub ec_icdf: &'static [u8],
    /// Minimum spacing, `order + 1` entries in Q15.
    pub delta_min_q15: &'static [i16],
}

