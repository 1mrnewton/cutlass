#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_slots_match_the_type_table() {
        assert_eq!(MetaType::Video.value(), 1);
        assert_eq!(MetaType::Video.as_str(), "video");
        assert_eq!(MetaType::parse("speed"), Some(MetaType::Speed));
        assert_eq!(MetaType::from_value(62), Some(MetaType::VideoOriginalSound));
        assert_eq!(
            MetaType::VideoOriginalSound.as_str(),
            "video_original_sound"
        );
        assert_eq!(MetaType::from_value(41), None);
        assert_eq!(MetaType::from_value(127), Some(MetaType::AiGenerateText));
        assert_eq!(MetaType::parse(""), None);
        assert_eq!(MetaType::from_value(0).unwrap().as_str(), "none");
    }
}
