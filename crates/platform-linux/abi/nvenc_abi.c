/*
 * Prints src/video/imp/nvenc_abi.rs: the sizes, field offsets, bitfield
 * positions, GUIDs and enum values of nvEncodeAPI.h that the NVENC encoder
 * uses. The structs are large and mostly reserved, so the Rust side keeps
 * each one as zeroed bytes and writes fields at these offsets.
 *
 * Built against FFmpeg's nv-codec-headers n12.0.16.1 (NVENC API 12.0, MIT)
 * on an LP64 host, where the layout is the same as on 64-bit Linux:
 *
 *   cc -I nv-codec-headers/include abi/nvenc_abi.c -o nvenc_abi
 *   ./nvenc_abi > src/video/imp/nvenc_abi.rs && cargo fmt -p cutlass-platform-linux
 */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <ffnvcodec/nvEncodeAPI.h>

static void line(const char *name, size_t value) {
    printf("    pub const %s: usize = %zu;\n", name, value);
}

static void open_mod(const char *name, const char *doc) {
    printf("\n/// %s\npub mod %s {\n", doc, name);
}

static void close_mod(void) { printf("}\n"); }

/* The u32 word, shift and width of a bitfield, found by setting every bit
 * of it in a zeroed struct. */
static void bits(const char *name, const unsigned char *bytes, size_t len) {
    for (size_t word = 0; word + 4 <= len; word += 4) {
        uint32_t value;
        memcpy(&value, bytes + word, 4);
        if (value) {
            unsigned shift = (unsigned)__builtin_ctz(value);
            unsigned width = (unsigned)__builtin_popcount(value);
            printf("    pub const %s: super::Bits = super::Bits { offset: %zu, shift: %u, width: %u };\n",
                   name, word, shift, width);
            return;
        }
    }
    printf("    compile_error!(\"%s not found\");\n", name);
}

#define BITS(T, NAME, FIELD, ONES)                     \
    do {                                               \
        T s;                                           \
        memset(&s, 0, sizeof s);                       \
        s.FIELD = ONES;                                \
        bits(NAME, (const unsigned char *)&s, sizeof s); \
    } while (0)

static void guid(const char *name, GUID g) {
    unsigned char b[16];
    memcpy(b, &g, 16);
    printf("pub const %s: [u8; 16] = [", name);
    for (int i = 0; i < 16; i++) printf("%s0x%02x", i ? ", " : "", b[i]);
    printf("];\n");
}

#define U32(NAME, VALUE) printf("pub const %s: u32 = %u;\n", NAME, (unsigned)(VALUE))
#define I32(NAME, VALUE) printf("pub const %s: i32 = %d;\n", NAME, (int)(VALUE))

