#define IS_SIGNED(x) ((__typeof__(x))-1 < 0)

static const char *kind(size_t size, int sign) {
    switch (size) {
    case 1: return sign ? "I8" : "U8";
    case 2: return sign ? "I16" : "U16";
    case 4: return sign ? "I32" : "U32";
    case 8: return "U64";
    }
    return "Unknown";
}

static void open_mod(const char *name, const char *doc, size_t size) {
    printf("\n/// %s\npub mod %s {\n    #[allow(unused_imports, clippy::wildcard_imports)]\n    use super::*;\n\n", doc, name);
    printf("    pub const SIZE: usize = %zu;\n", size);
}

static void close_mod(void) { printf("}\n"); }

#define M(T) ((T *)0)

/* A scalar field. */
#define F(T, NAME, f)                                                                \
    do {                                                                             \
        const char *k = kind(sizeof(M(T)->f), IS_SIGNED(M(T)->f));                   \
        printf("    pub const %s: %s = %s(%zu);\n", NAME, k, k, offsetof(T, f));     \
    } while (0)

/* An array of scalars, one or two dimensions, row by row. */
#define A(T, NAME, f, ELEM)                                                          \
    do {                                                                             \
        size_t e = sizeof(M(T)->ELEM);                                               \
        printf("    pub const %s: Array<%s> = Array::new(%zu, %zu, %zu);\n", NAME,   \
               kind(e, IS_SIGNED(M(T)->ELEM)), offsetof(T, f), sizeof(M(T)->f) / e, e); \
    } while (0)

/* An array of structs. */
#define SA(T, NAME, f)                                                               \
    do {                                                                             \
        size_t e = sizeof(M(T)->f[0]);                                               \
        printf("    pub const %s: Array<Base> = Array::new(%zu, %zu, %zu);\n", NAME, \
               offsetof(T, f), sizeof(M(T)->f) / e, e);                              \
    } while (0)

/* A struct inside the struct. */
#define S(T, NAME, f) printf("    pub const %s: Base = Base(%zu);\n", NAME, offsetof(T, f))

/* A bitfield, found by setting all of its bits in a zeroed struct. */
#define B(T, NAME, f)                                                                \
    do {                                                                             \
        T s;                                                                         \
        memset(&s, 0, sizeof s);                                                     \
        s.f = -1;                                                                    \
        bits(NAME, (const unsigned char *)&s, sizeof s);                             \
    } while (0)

static void bits(const char *name, const unsigned char *bytes, size_t len) {
    for (size_t word = 0; word + 4 <= len; word += 4) {
        uint32_t value;
        memcpy(&value, bytes + word, 4);
        if (value) {
            printf("    pub const %s: Bits = Bits { offset: %zu, shift: %u, width: %u };\n", name,
                   word, (unsigned)__builtin_ctz(value), (unsigned)__builtin_popcount(value));
            return;
        }
    }
    printf("    compile_error!(\"%s not found\");\n", name);
}

