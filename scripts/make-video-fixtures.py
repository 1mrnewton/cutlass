#!/usr/bin/env python3
"""Regenerate the synthetic video fixtures in fixtures/video/.

Needs ffmpeg and ffprobe built with libx264 and libx265. Tests never run this;
they read the committed output. FFmpeg's decoder supplies the expected frame
checksums, which is valid because H.264 and HEVC decoding is bit-exact.

Usage: scripts/make-video-fixtures.py [fixture-name ...]
"""

import json
import subprocess
import sys
import tempfile
import zlib
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "fixtures" / "video"
FRAMES = 12

# Fixed GOPs of 6 with two B-frames between references, so every stream has
# reordering and more than one keyframe.
X264 = "keyint=6:min-keyint=6:scenecut=0:bframes=2:b-adapt=0"
X265 = X264 + ":info=0:log-level=error"


@dataclass
class Fixture:
    name: str
    codec: str
    width: int
    height: int
    source_pix_fmt: str
    output_pix_fmt: str
    color_range: str
    encode: list = field(default_factory=list)


def h264(name, width, height, color_range="limited"):
    return Fixture(
        name, "h264", width, height, "yuv420p", "nv12", color_range,
        ["-c:v", "libx264", "-profile:v", "high", "-x264-params", X264,
         # Drop SEI, which holds the x264 version and settings string.
         "-bsf:v", "filter_units=remove_types=6"],
    )


def hevc(name, width, height, ten_bit=False):
    return Fixture(
        name, "hevc", width, height,
        "yuv420p10le" if ten_bit else "yuv420p",
        "p010le" if ten_bit else "nv12",
        "limited",
        ["-c:v", "libx265", "-x265-params", X265, "-tag:v", "hvc1"],
    )


FIXTURES = [
    h264("h264-high-bframes-128x72", 128, 72),
    h264("h264-high-full-range-128x72", 128, 72, color_range="full"),
    h264("h264-high-cropped-100x58", 100, 58),
    hevc("hevc-main-bframes-128x72", 128, 72),
    hevc("hevc-main10-bframes-128x72", 128, 72, ten_bit=True),
]


def run(args, binary=False):
    result = subprocess.run(args, check=True, capture_output=True)
    return result.stdout if binary else result.stdout.decode()


def hexdump_bytes(dump):
    """Parse ffprobe's -show_data dump: offset, eight hex groups, ASCII."""
    data = bytearray()
    for line in dump.splitlines():
        if line:
            data += bytes.fromhex(line[10:50])
    return bytes(data)


def frame_size(fixture):
    luma = fixture.width * fixture.height
    chroma = (fixture.width // 2) * (fixture.height // 2) * 2
    bytes_per_sample = 2 if fixture.output_pix_fmt == "p010le" else 1
    return (luma + chroma) * bytes_per_sample


def generate(fixture, work):
    clip = work / f"{fixture.name}.mp4"
    ffmpeg_range = "pc" if fixture.color_range == "full" else "tv"
    run([
        "ffmpeg", "-v", "error", "-y",
        "-f", "lavfi", "-i", f"testsrc2=size={fixture.width}x{fixture.height}:rate=30",
        "-frames:v", str(FRAMES), "-pix_fmt", fixture.source_pix_fmt,
        "-color_range", ffmpeg_range, *fixture.encode, "-an", str(clip),
    ])

    probe = json.loads(run([
        "ffprobe", "-v", "error", "-select_streams", "v:0",
        "-show_streams", "-show_packets", "-show_data", "-of", "json", str(clip),
    ]))
    stream = probe["streams"][0]
    config = hexdump_bytes(stream["extradata"])
    assert len(config) == int(stream["extradata_size"]), "extradata parse"
    numerator, timescale = stream["time_base"].split("/")
    assert numerator == "1", stream["time_base"]

    packets = []
    for packet in probe["packets"]:
        data = hexdump_bytes(packet["data"])
        assert len(data) == int(packet["size"]), "packet parse"
        packets.append((packet, data))
    assert len(packets) == FRAMES, f"{len(packets)} packets"

    frames = json.loads(run([
        "ffprobe", "-v", "error", "-select_streams", "v:0",
        "-show_entries", "frame=pts", "-of", "json", str(clip),
    ]))["frames"]
    raw = run([
        "ffmpeg", "-v", "error", "-i", str(clip), "-fps_mode", "passthrough",
        "-vf", f"scale=in_range={fixture.color_range}:out_range={fixture.color_range}",
        "-f", "rawvideo", "-pix_fmt", fixture.output_pix_fmt, "-",
    ], binary=True)
    size = frame_size(fixture)
    assert len(raw) == size * len(frames) == size * FRAMES, "decoded frame count"

    luma = raw[: fixture.width * fixture.height]
    if fixture.color_range == "full" and fixture.output_pix_fmt == "nv12":
        assert min(luma) < 16 or max(luma) > 235, "full range was converted to limited"

    out = OUT / fixture.name
    out.mkdir(parents=True, exist_ok=True)
    (out / "config.bin").write_bytes(config)
    (out / "packets.bin").write_bytes(b"".join(data for _, data in packets))

    pixel_format = "p010" if fixture.output_pix_fmt == "p010le" else "nv12"
    lines = [
        "# Generated by scripts/make-video-fixtures.py. Do not edit.",
        f"codec {fixture.codec}",
        f"width {fixture.width}",
        f"height {fixture.height}",
        f"timescale {timescale}",
        f"pixel_format {pixel_format}",
        f"color_range {fixture.color_range}",
    ]
    for packet, data in packets:
        keyframe = "K" if "K" in packet["flags"] else "-"
        lines.append(
            f"packet {packet['pts']} {packet.get('dts', '-')} "
            f"{packet.get('duration', '-')} {keyframe} {len(data)}"
        )
    for index, frame in enumerate(frames):
        crc = zlib.crc32(raw[index * size : (index + 1) * size])
        lines.append(f"frame {frame['pts']} {crc:08x}")
    (out / "stream.txt").write_text("\n".join(lines) + "\n")

    total = len(config) + sum(len(data) for _, data in packets)
    print(f"{fixture.name}: {len(packets)} packets, {total} bytes")


def main():
    wanted = set(sys.argv[1:])
    unknown = wanted - {fixture.name for fixture in FIXTURES}
    if unknown:
        sys.exit(f"unknown fixtures: {', '.join(sorted(unknown))}")
    print(run(["ffmpeg", "-version"]).splitlines()[0])
    with tempfile.TemporaryDirectory() as work:
        for fixture in FIXTURES:
            if not wanted or fixture.name in wanted:
                generate(fixture, Path(work))


if __name__ == "__main__":
    main()
